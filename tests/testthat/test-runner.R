test_that("runner reads preserve actual jobs, dimensions, provenance, and scoped overrides", {
    root <- local_runner_output()
    runs <- lpjguessRunner::list_simulations(root)
    dt <- read_runner(root, "dave_lai")
    expect_s3_class(dt, "data.table")
    expect_equal(nrow(dt), 6L)
    expect_setequal(dt$variable, "total")
    expect_equal(length(unique(dt$run_id)), 3L)
    expect_equal(unique(dt[simulation == "baseline"]$simulation_key), "baseline")
    expect_setequal(dt$instruction_file, c("SiteA", "SiteB"))
    expect_equal(dt$Date, rep(as.POSIXct(c("2024-01-01", "2024-01-02"), tz = ""), 3L))
    expect_true(all(c("stand", "patch", "base_ins", "ins_file", "output_path") %in% names(dt)))
    expect_identical(unique(dt$output_file), "custom-lai.out")
    expect_identical(unique(dt$output), "dave_lai")
    expect_identical(dt[["param:pft:MRS:sla"]], c("26", "26", "39", "39", "26", "26"))
    expect_setequal(dt[["param:nindiv_max"]], c("0", "1"))
    expect_equal(read_runner(runs, "file_dave_lai"), dt)
    expect_equal(read_runner(runs, "custom-lai.out"), dt)
    expect_equal(read_runner(list(output_directory = root), "dave_lai"), dt)
    expect_equal(read_runner(structure(list(output_directory = root), class = "lpjguess_result"), "dave_lai"), dt)
    expect_equal(nrow(read_runner(runs[runs$instruction_file == "SiteA", ], "dave_lai")), 4L)
})

test_that("runner selections filter jobs and distinguish absent overrides and scopes", {
    skip_if_not_installed("lpjguessRunner")
    factors <- list(list(), list(lpjguessRunner::block_parameter("pft", "MRS", "sla", 39),
        lpjguessRunner::block_parameter("pft", "Other", "sla", 26)),
        list(lpjguessRunner::top_level_parameter("sla", 10)))
    root <- local_runner_output(factors = factors)
    parameters <- runner_parameters(root)
    expect_setequal(parameters$parameter, c("pft:MRS:sla", "pft:Other:sla", "sla"))
    expect_equal(nrow(parameters), 3L)
    expect_type(parameters$value, "character")
    expect_equal(nrow(read_runner(root, "dave_lai", simulations = "baseline")), 4L)
    expect_equal(nrow(read_runner(root, "dave_lai", instruction_files = "SiteA")), 4L)
    chosen <- read_runner(root, "dave_lai", parameters = list("pft:MRS:sla" = 39))
    expect_identical(unique(chosen$simulation), "treatment")
    absent <- read_runner(root, "dave_lai", parameters = list("pft:MRS:sla" = NA_character_))
    expect_equal(nrow(absent), 4L)
    expect_true(all(is.na(absent[["param:pft:MRS:sla"]])))
    expect_error(read_runner(root, "dave_lai", parameters = list("sla" = 99)), "No runner simulations")
    expect_error(read_runner(root, "dave_lai", simulations = "typo"), "Unknown simulations")
    expect_error(read_runner(root, "dave_lai", instruction_files = "typo"), "Unknown instruction_files")
    expect_error(read_runner(root, "dave_lai", parameters = list(slal = 26)), "Unknown parameters")
    expect_error(read_runner(root, "dave_lai", parameters = c(sla = 26)), "named list")
})

