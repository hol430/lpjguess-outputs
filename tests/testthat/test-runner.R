test_that("freshness is measured within each actual job before filtering outputs", {
    root <- local_runner_output()
    runs <- .runner_runs(root)
    time <- as.POSIXct("2024-01-01", tz = "UTC")
    for (i in 1:3) {
        directory <- file.path(runs$path[[i]], "results")
        extra <- file.path(directory, "newest.out")
        file.copy(file.path(directory, "custom-lai.out"), extra)
        Sys.setFileTime(extra, time + i * 86400)
        Sys.setFileTime(file.path(directory, "custom-lai.out"), time + i * 86400 - 10)
    }
    inventory <- .runner_inventory(runs, 10)
    expect_true(all(inventory$status == "Available"))
    expect_equal(nrow(read_runner(root, "dave_lai")), 6L)
    Sys.setFileTime(file.path(runs$path[[2]], "results", "custom-lai.out"), time + 2 * 86400 - 11)
    expect_error(read_runner(root, "dave_lai"), "SiteA/treatment: dave_lai \\(Stale\\)")
    expect_warning(available <- read_runner(root, "dave_lai", missing = "warn"), "Stale")
    expect_equal(nrow(available), 4L)
    expect_equal(nrow(read_runner(root, "dave_lai", missing = "ignore")), 4L)
    expect_equal(nrow(read_runner(root, "dave_lai", stale_threshold_secs = Inf)), 6L)
    expect_identical(.runner_common_outputs(.runner_inventory(runs, 10), runs), "newest")
    for (invalid in list(-1, NA_real_, "10", numeric())) {
        expect_error(read_runner(root, "dave_lai", stale_threshold_secs = invalid), "stale_threshold_secs")
    }
})

test_that("missing and empty requested files never silently remove a job", {
    root <- local_runner_output()
    runs <- .runner_runs(root)
    path <- file.path(runs$path[[2]], "results", "custom-lai.out")
    unlink(path)
    expect_error(read_runner(root, "dave_lai"), "SiteA/treatment: dave_lai \\(Missing\\)")
    expect_equal(nrow(read_runner(root, "dave_lai", missing = "ignore")), 4L)
    file.create(path)
    expect_error(read_runner(root, "dave_lai"), "Empty")
    frame <- data.frame(Lon = numeric(), Lat = numeric(), Year = integer(), total = numeric())
    write_runner_output(root, frame, job = 2L)
    expect_error(read_runner(root, "dave_lai"), "no data rows")
    expect_error(read_runner(root, character()), "non-empty character")
    expect_error(read_runner(root, "missing", missing = "ignore"), "No readable")
    empty <- local_runner_output(data.frame(instruction = character(), simulation = character()))
    expect_equal(nrow(runner_parameters(empty)), 0L)
    expect_error(read_runner(empty, "dave_lai"), "No runner simulations")
})

test_that("each schema is reshaped separately and subdaily days are zero based", {
    root <- local_runner_output()
    first <- data.frame(Lon = 150, Lat = -33, Year = 2024L,
        Day = c(0L, 59L, 365L), timestep = c(0L, 12L, 23L), total = 1:3)
    write_runner_output(root, first, 1L)
    second <- data.frame(Lon = 150, Lat = -33, Year = 2024L, Day = 0L,
        layer = 0:1, depth_top = c(0, 10), depth_bottom = c(10, 30), wmass = c(2, 3))
    write_runner_output(root, second, 1L, "soil.out")
    dt <- read_runner(root, c("dave_lai", "dave_soil_state"), instruction_files = "SiteA", simulations = "baseline")
    expect_equal(nrow(dt), 5L)
    expect_setequal(dt$variable, c("total", "wmass"))
    expect_equal(dt[output == "dave_lai"]$Date,
        as.POSIXct(c("2024-01-01 00:00:00", "2024-02-29 12:00:00", "2024-12-31 23:00:00"), tz = "", format = "%Y-%m-%d %H:%M:%S"))
    expect_equal(sum(is.na(dt$value)), 0L)
    expect_setequal(dt[output == "dave_soil_state"]$layer, 0:1)
})

test_that("standard monthly files become monthly observations and separate annual summaries", {
    root <- local_runner_output()
    monthly <- data.frame(Lon = 150, Lat = -33, Year = 2024L)
    for (i in seq_along(month.abb)) monthly[[month.abb[[i]]]] <- i
    monthly$Total <- 78
    write_runner_output(root, monthly, 1L, "monthly.out")
    dt <- read_runner(root, "mnpp", instruction_files = "SiteA", simulations = "baseline")
    expect_equal(nrow(dt), 13L)
    expect_equal(dt[variable == "monthly"]$value, as.numeric(1:12))
    expect_equal(format(dt[variable == "monthly"]$Date, "%m-%d"), sprintf("%02d-01", 1:12))
    expect_equal(format(dt[variable == "Total"]$Date, "%m-%d"), "12-31")
    expect_no_error(ggplot2::ggplot_build(plot_runner(root, "mnpp", instruction_files = "SiteA", simulations = "baseline")))
})

